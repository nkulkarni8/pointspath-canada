from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker
from config import settings

SQLALCHEMY_DATABASE_URL = settings.DATABASE_URL

if "sqlite" in SQLALCHEMY_DATABASE_URL:
    engine = create_engine(SQLALCHEMY_DATABASE_URL, connect_args={"check_same_thread": False})
    print("✅ Using SQLite (development)")
else:
    engine = create_engine(SQLALCHEMY_DATABASE_URL, pool_pre_ping=True, pool_recycle=3600)
    print("✅ Using PostgreSQL (production)")

SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()

def init_db():
    from models import Base
    Base.metadata.create_all(bind=engine)
    print("✅ Database tables ready")

def seed_database():
    from models import CreditCard, Route
    db = SessionLocal()
    try:
        if db.query(CreditCard).count() > 0:
            print("ℹ️  DB already seeded — running incremental route patch...")
            _patch_missing_routes(db)
            return
        print("🌱 Seeding database...")
        _seed_cards(db)
        _seed_routes(db)
        _seed_hk(db)
        _seed_extra_routes(db)
        print("🎉 Seeding complete!")
    except Exception as e:
        print(f"❌ Seed error: {e}")
        import traceback; traceback.print_exc()
        db.rollback()
    finally:
        db.close()


